#!/usr/bin/env node
/* =========================================================================
   Behance importer — run:  node tools/import-behance.mjs
   -------------------------------------------------------------------------
   Sources (both are public, no login / API key needed):
     1. Your Behance RSS feed  → your 12 most recent projects (Behance caps it)
     2. behance-urls.txt       → any extra project URLs you paste (one per line)
   For every project the official embed page is read for the real title and
   cover. Output: behance-projects.js (loaded by the website).
   Optional category override in behance-urls.txt:   URL | category-key
   ========================================================================= */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const USER = "mnaouarsaad";
const UA = "Mozilla/5.0 (compatible; PortfolioImporter/1.0)";
const get = async u => { const r = await fetch(u, { headers: { "User-Agent": UA } }); if (!r.ok) throw new Error(`${r.status} ${u}`); return r.text(); };

/* keyword → category (first match wins). Edit freely. */
const RULES = [
  [/football|soccer|match ?day|sport/i, "football"],
  [/social|post|story|stories|carousel|instagram|feed/i, "social"],
  [/logo|brand|identity/i, "brand"],
  [/food|burger|pizza|restaurant|menu|coffee|cafe|drink|beverage/i, "food"],
  [/poster|flyer/i, "posters"],
  [/print|brochure|card|catalog|roll-?up|banner/i, "print"],
  [/pack|box|bottle|label|mockup|product/i, "packaging"],
  [/motion|animation|reel|ai video|3d/i, "motion"],
  [/video|edit/i, "video"],
  [/web|ui|ux|app|landing|dashboard/i, "web"]
];
const guess = t => (RULES.find(([re]) => re.test(t)) || [, "other"])[1];

const decode = s => s.replace(/<!\[CDATA\[|\]\]>/g, "").trim();
const idOf = u => (u.match(/gallery\/(\d+)/) || u.match(/project\/(\d+)/) || [])[1];

async function fromFeed() {
  const xml = await get(`https://www.behance.net/feeds/user?username=${USER}`);
  return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].map(m => {
    const it = m[1], g = t => decode((it.match(new RegExp(`<${t}>([\\s\\S]*?)</${t}>`)) || [, ""])[1]);
    return { id: idOf(g("link")), url: g("link"), title: g("title"), date: g("pubDate") };
  });
}
async function fromFile() {
  try {
    return (await readFile(path.join(ROOT, "behance-urls.txt"), "utf8")).split(/\r?\n/)
      .map(l => l.replace(/#.*/, "").trim()).filter(Boolean)
      .map(l => { const [url, cat] = l.split("|").map(s => s.trim()); return { id: idOf(url), url, cat }; })
      .filter(p => p.id);
  } catch { return []; }
}
async function embed(id) {
  const html = await get(`https://www.behance.net/embed/project/${id}?ilo0=1`);
  const raw = (html.match(/id="beconfig-store_state">([\s\S]*?)<\/script>/) || [])[1];
  const p = JSON.parse(raw).embedStore.project;
  const c = p.covers || {};
  return { title: p.name, url: p.url, cover: (c.size_808_webp || c.size_max_808_webp || c.size_404_webp || {}).url,
           coverLg: (c.size_original_webp || c.size_808_webp || {}).url };
}
const shapeOf = url => { // Behance encodes the crop (e.g. "crop,1400,1095,0,3") in the filename
  try { const [, w, h] = Buffer.from(url.split("/").pop().split(".")[1], "base64").toString().split(","); const r = w / h;
    return r > 1.9 ? "wide" : r > 1.1 ? "landscape" : r < .9 ? "portrait" : "square"; } catch { return "landscape"; }
};

const seen = new Map();
for (const p of [...await fromFile(), ...await fromFeed()]) if (p.id && !seen.has(p.id)) seen.set(p.id, p);

const out = [];
for (const p of seen.values()) {
  try {
    const e = await embed(p.id);
    const title = e.title || p.title;
    out.push({
      id: "be-" + p.id, behanceId: p.id, title, category: p.cat || guess(title), categories: [p.cat || guess(title)],
      year: p.date ? String(new Date(p.date).getFullYear()) : "",
      shape: e.cover ? shapeOf(e.cover) : "landscape",
      cover: e.cover || "", coverLg: e.coverLg || "", images: [],
      link: e.url || p.url, embed: `https://www.behance.net/embed/project/${p.id}?ilo0=1`
    });
    console.log("✓", p.id, title);
  } catch (err) { console.warn("✗", p.id, err.message); }
}
await writeFile(path.join(ROOT, "behance-projects.js"),
  `/* AUTO-GENERATED by tools/import-behance.mjs — ${new Date().toISOString()}. Re-run to refresh. */\nwindow.BEHANCE_PROJECTS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`\nImported ${out.length} projects → behance-projects.js`);
