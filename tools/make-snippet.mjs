#!/usr/bin/env node
/* Build a browser snippet for specific projects only.
     node tools/make-snippet.mjs <behance-url-or-id> [more urls/ids …]
   Writes tools/browser-snippet-<first-id>.js — paste it into Chrome's console on any
   https://www.behance.net page (signed in, so your own mature-content projects are readable),
   then move the downloaded behance-dump.json into the site folder and run:
     node tools/import-assets.mjs
   (add --include-existing ONLY if the project is one of your original 12.) */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HERE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ids = [...new Set(process.argv.slice(2).map(a => (a.match(/(\d{6,})/) || [])[1]).filter(Boolean))];
if (!ids.length) { console.error("Usage: node tools/make-snippet.mjs <behance-url-or-id> …"); process.exit(1); }

const base = await readFile(path.join(HERE, "tools/behance-console-snippet.js"), "utf8");
const start = base.indexOf("  // 1. load the whole profile");
const marker = "  log(`found ${links.size} projects on the profile`);";
const end = base.indexOf(marker);
if (start < 0 || end < 0) { console.error("Template changed — cannot build snippet."); process.exit(1); }

const urls = Object.fromEntries(ids.map(id => [id, `https://www.behance.net/gallery/${id}`]));
let out = base.slice(0, start) + `  // 1. ONLY the project URLs listed in NEW_URLS (above) are opened — nothing else
  if (location.hostname !== "www.behance.net") { console.log("Open any page on https://www.behance.net first, then paste this again."); return; }
  const links = new Map(Object.entries(NEW_URLS));
  log(\`\${links.size} project(s) to export\`);` + base.slice(end + marker.length);
out = out.replace("(async () => {", `const NEW_URLS = ${JSON.stringify(urls, null, 2)};   // <- the only pages this script will request\n(async () => {`)
  .replace(/RUN THIS IN YOUR OWN BROWSER[^\n]*\n[\s\S]*?\n   It only reads/, "RUN THIS IN YOUR OWN BROWSER — SELECTED PROJECTS ONLY (generated by tools/make-snippet.mjs)\n   Open ANY page on https://www.behance.net (signed in), open the console, paste this whole file, Enter.\n   It exports only the projects in NEW_URLS below. Then run: node tools/import-assets.mjs\n   It only reads");

const file = path.join(HERE, `tools/browser-snippet-${ids[0]}.js`);
await writeFile(file, out);
console.log(`Wrote ${path.relative(HERE, file)} for: ${ids.join(", ")}`);
